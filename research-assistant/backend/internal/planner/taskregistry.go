func lookupTaskTypeSpec(taskType string) (TaskTypeSpec, bool) {
	taskType = strings.TrimSpace(taskType)
	if spec, ok := taskTypeRegistry[taskType]; ok {
		return spec, true
	}
	if strings.HasPrefix(taskType, "framework_fit_") {
		return taskTypeRegistry["framework_fit_*"], true
	}
	return TaskTypeSpec{}, false
}

func (s TaskTypeSpec) allowsAgent(agent string) bool {
	agent = strings.TrimSpace(agent)
	for _, allowed := range s.AllowedAgents {
		if agent == allowed {
			return true
		}
	}
	return false
}

// validateTaskNode checks a single planner node against the registry.
func validateTaskNode(node *models.TaskNode) error {
	if node == nil {
		return fmt.Errorf("task node is nil")
	}
	spec, ok := lookupTaskTypeSpec(node.Type)
	if !ok {
		return fmt.Errorf("task type %q is not registered in the task registry", node.Type)
	}
	if spec.ExecutionKind == ExecutionDead {
		return fmt.Errorf("task type %q is dead and must not be planned: %s", node.Type, spec.Description)
	}
	if !spec.allowsAgent(node.AssignedTo) {
		return fmt.Errorf("task type %q must be assigned to %s, got %q", node.Type, strings.Join(spec.AllowedAgents, " or "), node.AssignedTo)
	}
	for _, artifact := range spec.RequiredOutputArtifacts {
		if !containsArtifact(node.OutputArtifacts, artifact) {
			return fmt.Errorf("task type %q must output artifact %q", node.Type, artifact)
		}
	}
	return nil
}

// validateTaskRegistry checks every node in a plan before it is accepted.
func validateTaskRegistry(nodes []*models.TaskNode) error {
	for _, node := range nodes {
		if err := validateTaskNode(node); err != nil {
			return err
		}
	}
	return nil
}

// registeredTaskTypeNames returns concrete registry keys for coverage tests.
func registeredTaskTypeNames() []string {
	names := make([]string, 0, len(taskTypeRegistry))
	for name, spec := range taskTypeRegistry {
		if spec.ExecutionKind != ExecutionDead {
			names = append(names, name)
		}
	}
	return names
}
